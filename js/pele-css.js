/**
 * CSS for the Pele playground (its "CSS" tab), so a diagram pasted there looks
 * like it does in this app.
 *
 * Pele is themed with CSS custom properties on `.pele` (https://pele.run/theming).
 * The theme's variables are written as such. For Gantt charts the CSS also
 * reproduces what gantt-style.js does to the SVG in this app – PIs black,
 * sprints grey, a colour per section, statuses and row stripes – using the task
 * ids that the generated Mermaid code contains ("pi1", "s3", "g0t2").
 * Not possible in CSS: shortening labels that run into the next bar.
 */
import { themeVars, rowColour, PELE_DEFAULTS } from './themes.js';
import { calendarOf, sectionColour } from './gantt.js';

function luminance(hex) {
  const m = /^#?([0-9a-f]{6})$/i.exec(hex || '');
  if (!m) return 0;
  const [r, g, b] = [0, 2, 4].map((i) => {
    const c = parseInt(m[1].slice(i, i + 2), 16) / 255;
    return c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4;
  });
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}

const block = (selector, decls) =>
  `${selector} {\n${Object.entries(decls)
    .map(([k, v]) => `  ${k}: ${v};`)
    .join('\n')}\n}`;

/** Selector for a list of task ids, e.g. `.pele-task:is([data-id="pi1"], [data-id="pi2"])`. */
const tasks = (ids) => `.pele-gantt .pele-task:is(${ids.map((id) => `[data-id="${id}"]`).join(', ')})`;

/**
 * @param {object} state app state (theme, disableMulticolor, mode, gantt)
 * @param {Set<string>} [insideLabels] task ids whose label sits on the bar (from styleGantt)
 * @returns {string} CSS for the Pele playground
 */
export function peleCss(state, insideLabels = new Set()) {
  const gantt = state.mode === 'gantt';
  // A complete set (Pele defaults + theme), so it fully replaces the playground's own theme.
  const vars = { ...PELE_DEFAULTS, ...themeVars(state.theme, !gantt && state.disableMulticolor) };
  const out = [
    `/* Pele playground CSS – generated by Timeline Builder (theme: ${state.theme}). */`,
    block('.pele', vars),
  ];
  if (!gantt) return out.join('\n\n') + '\n';

  const g = state.gantt;
  const cal = calendarOf(g);
  const shape = (sel) => `${sel} > :is(rect, path)`;
  const inside = (sel) => `${sel} > .pele-label[fill]`; // labels drawn on the bar

  // PIs in the foreground colour, sprints in grey (colour is left to the sections)
  if (cal.pis.length) {
    const sel = tasks(cal.pis.map((p) => p.id));
    out.push('/* PIs */', block(shape(sel), { fill: 'var(--pele-fg)', stroke: 'var(--pele-fg)' }), block(inside(sel), { fill: 'var(--pele-bg)' }));
  }
  if (cal.sprints.length) {
    const sel = tasks(cal.sprints.map((s) => s.id));
    out.push('/* Sprints */', block(shape(sel), { fill: 'var(--pele-muted)', stroke: 'var(--pele-muted)' }), block(inside(sel), { fill: 'var(--pele-bg)' }));
  }

  // One colour per section (category); "critical" keeps Pele's red
  g.sections.forEach((sec, si) => {
    const ids = sec.tasks.map((_, ti) => `g${si}t${ti}`);
    if (!ids.length) return;
    const k = sectionColour(g, si);
    const colour = `var(--pele-series-${k})`;
    const sel = `${tasks(ids)}:not(.pele-crit)`;
    const light = luminance(vars[`--pele-series-${k}`]) > 0.45;
    out.push(
      `/* Section "${String(sec.name).replace(/\*\//g, '')}" */`,
      block(shape(sel), { fill: colour, stroke: colour, 'fill-opacity': '1' }),
      block(inside(`${sel}:not(.pele-done)`), { fill: light ? 'var(--pele-fg)' : '#ffffff' }),
    );
  });

  // Status: done = faded, in progress = outlined
  out.push(
    '/* Status */',
    block('.pele-gantt .pele-task.pele-done:not(.pele-crit) > :is(rect, path)', { 'fill-opacity': '0.35' }),
    // (more specific than the section rule, which also sets the stroke)
    block('.pele-gantt g.pele-task.pele-active[data-id] > :is(rect, path)', { stroke: 'var(--pele-fg)', 'stroke-width': '1.5' }),
  );
  // Pele does not mark whether the label of an "in progress" task sits on the bar
  // (it draws those bars light). The app's last layout tells: colour those labels.
  g.sections.forEach((sec, si) => {
    const k = sectionColour(g, si);
    const light = luminance(vars[`--pele-series-${k}`]) > 0.45;
    const ids = sec.tasks
      .map((t, ti) => (t.status === 'active' && insideLabels.has(`g${si}t${ti}`) ? `g${si}t${ti}` : null))
      .filter(Boolean);
    if (ids.length) out.push(block(`${tasks(ids)} > .pele-label`, { fill: light ? 'var(--pele-fg)' : '#ffffff' }));
  });

  // Row stripes
  const [a, b] = (g.rows ?? ['surface', 'none']).map((t) => rowColour(t, vars));
  out.push(
    '/* Row stripes */',
    block('.pele-gantt .pele-sections > rect:nth-child(odd)', { fill: a }),
    block('.pele-gantt .pele-sections > rect:nth-child(even)', { fill: b }),
  );
  return out.join('\n\n') + '\n';
}
